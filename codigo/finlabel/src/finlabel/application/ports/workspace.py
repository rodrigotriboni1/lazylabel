"""Effects needed by the shared interactive application entry points.

These ports preserve local artifact/configuration contracts without exposing any
framework or concrete adapter to application orchestration. References are opaque
to the application; filesystem access is owned by the implementation.
"""
from typing import Any, Callable, Mapping, NewType, Protocol

from finlabel.application.ports.projects import ProjectMetadata
from finlabel.application.ports.sources import ReadOnlySource


ProjectHandle = NewType("ProjectHandle", object)


class TrainingJobStatus(Protocol):
    """Privacy-safe status fields required by inbound presentation adapters."""

    job_id: str
    state: str
    progress: str
    error: str | None
    model_id: str
    dataset_sha256: str
    final_metrics: Mapping[str, float]


class WorkspaceOperations(Protocol):
    def inspect(self, path: str, target: str | None = None) -> dict: ...
    def initialize(self, path: str) -> object: ...
    def project(self, reference: str) -> ProjectHandle: ...
    def project_metadata(self, project: ProjectHandle) -> ProjectMetadata: ...
    def source(self, project: ProjectHandle, name: str) -> ReadOnlySource: ...
    def configure_source(self, project: str, command: str, name: str,
                         path: str | None = None, **options: Any) -> dict: ...
    def register_supervision(self, project: str, source: str, task: str,
                             label_column: str, provenance: str, trust_kind: str,
                             label_map: str | None = None, refresh: bool = False) -> dict: ...
    def add_task(self, project: str, file: str) -> object: ...
    def task(self, project: Any, task_id: str, columns: tuple | None = None) -> Any: ...
    def save_baseline(self, baseline: Any, path: str) -> None: ...
    def confirm_baseline(self, project: Any, source_name: str, baseline: Any) -> object: ...
    def monitor_baseline(self, project: Any, source_name: str, path: str | None = None) -> Any: ...
    def prepare_dataset(self, project: Any, run_id: str, output: str,
                        *, local_name: bool = False) -> Any: ...
    def train_request(self, project: Any, dataset: str, options: Mapping) -> Any: ...
    def submit_training(self, project: Any, dataset_name: str, model_id: str, options: Mapping) -> Any: ...
    def training_status(self, project: ProjectHandle, job_id: str) -> TrainingJobStatus | None: ...
    def model_status(self, project: Any, task_id: str) -> dict: ...
    def idempotent_run(self, project: Any, key: str, payload: dict, execute: Callable) -> dict: ...


class PanelQueries(Protocol):
    def overview(self, project_reference: str) -> dict: ...
    def suggestions(self, project_reference: str, run_id: str, limit: int) -> dict: ...
    def analysis_result(self, project: Any, run_id: str) -> dict | None: ...
    def analysis_payload(self, run: Any) -> dict: ...
    def chart_path(self, project: Any, run_id: str) -> object | None: ...


class PipelineArtifacts(Protocol):
    def read_label(self, run_id: str) -> dict: ...
    def read_pipeline(self, run_id: str) -> dict: ...
    def save_pipeline(self, run_id: str, payload: dict) -> dict: ...
    def cycle_digest(self, cycle: Any) -> str: ...
